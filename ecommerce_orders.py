import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from datetime import datetime
df =pd.read_excel("ecommerce_orders.xlsx")
pd.set_option('display.max_rows',None)
pd.set_option('display.max_columns',None)
pd.set_option('display.width',None)
df.columns = df.columns.str.strip()
text_col =["Customer_Name","Order_ID","Product","Category","Payment_Method","Status"]
for i in text_col:
    df[i]=df[i].astype(str).str.strip().str.title()
    df[i]=df[i].replace("nan",np.nan)
df["Order_Date"]=pd.to_datetime(df["Order_Date"],errors="coerce")
df["Quantity"] = pd.to_numeric(df["Quantity"],errors="coerce").astype("Int64")
df["Price"] = pd.to_numeric(df["Price"],errors="coerce")
df["Price"] = df.groupby("Product")["Price"].transform(lambda x:x.fillna(x.median()))
df=df.dropna(subset=["Quantity","Order_Date"])
# print(df.isnull().sum())
products_known_Category =df.loc[df["Category"].notna(),["Product","Category"]]
product_unknown_Category =df.loc[df["Category"].isnull(),["Product"]]
Product_category_map=(products_known_Category.drop_duplicates(subset="Product").set_index("Product")["Category"].to_dict())
mask = df["Category"].isna()
df.loc[mask,"Category"]=(df.loc[mask,"Product"].map(Product_category_map))
df["Total"]=(df["Quantity"]*df["Price"]).round(2)
max_category =df.groupby("Category").agg(revenu=("Total","sum"), items=("Quantity","sum")).sort_values("revenu",ascending=False)
# print(max_category)
max_product =df.groupby("Product").agg(revenu=("Total","sum"),items=("Quantity","sum")).sort_values("revenu",ascending=False)
# print(max_product)
pay_method =df.groupby("Payment_Method").agg(count=("Payment_Method","count")).sort_values("count",ascending=False).reset_index()
# print(pay_method)
status_count=df["Status"].value_counts().reset_index()
# print(status_count)
df["Order_Year"]=df["Order_Date"].dt.year
df["Order_Mounth"]=df["Order_Date"].dt.to_period("M")
order_By_Year = df.groupby("Order_Year").agg(revenu=("Total","sum"),items=("Quantity","sum")).sort_values("revenu",ascending=False).reset_index()
# print(order_By_Year)
order_By_Mounth =df.groupby("Order_Mounth").agg(revenu=("Total","sum"),items=("Quantity","sum")).reset_index()
